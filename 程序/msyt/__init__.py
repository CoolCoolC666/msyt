"""
msyt —— 民生e网通「群众留言板」舆情采集器
================================================
目标站：中国宁波网 民生e点通 · 天一论坛 › 群众留言板（fid=1176）

设计要点（全部来自实测，不是猜的）：
  1. 列表与详情**分离**。列表页元数据极丰富（类别/状态/部门/留言箱/回复数…），
     大部分分析用不着正文，先把列表扫完再按需补详情。
  2. 详情采集**先旧后新**（按发帖时间升序）。新帖会把旧帖往下推，
     先啃老的才能保证「存量先落袋」，且中断后从断点接着走即可。
  3. **断点续传**：工作队列在库里，每帖一个状态位，每页一个事务。
     进程被杀只会丢掉正在处理的那一页（那一帖不标 done），
     下次开机从 pages_done+1 接着走，已落库的楼层是校验过的正确数据。
  4. **头/尾完整性检验**：一帖必须同时拿到「头」（楼主那一楼）与
     「尾」（楼层号最大的那一楼）才算完整；且每页返回的 pid 集合必须与
     该页详情页锚点**完全相等**。少一页、串一帖，都会被当场拒收。
     另加一条独立交叉验证：列表页的「回复数 + 1」= 应有楼层数，
     实收少于它 ⇒ 不完整（这条不依赖任何解析，最硬）。
  5. **pid 是防串帖的锚**：ajax_getpost.php 的 tid 参数**不参与内容选择**，
     token 才是唯一钥匙（实测：用 A 帖 token 配 B 帖 tid，仍返回 A 帖正文）。
     所以必须做 pid 集合比对，不能只看 code=1。
  6. **站方标签直接当维度**：类别/受理状态/部门/区县市/留言箱/时效灯
     六条正交标签轴既做**采集源筛选**（每个切片一条独立分页列表，
     独立续传），也做**入库标签**（任意切片分析）。

模块：
    config.py      配置
    http_client.py 会话 / 限速 / 重试 / token 即取即用
    taxonomy.py    分类体系（109 部门 + 4 分组 + 10 区县市 + 类别/状态字典）
    sources.py     采集源注册表（把标签轴展开成可独立续传的采集源）
    parsers.py     列表行 / 详情页 / 楼层 / 受理流程 解析
    textutil.py    正文抽取与编码判定（移植 cacx）
    db.py          SQLite 落库 + 两张 FTS5 索引 + 组合检索（移植 cacx）
    listpage.py    链路一：列表采集
    detail.py      链路二：详情采集（先旧后新 / 断点续传 / 头尾完整性）
    doctor.py      接口自检
    cli.py         命令行
"""

